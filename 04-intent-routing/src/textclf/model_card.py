"""Generate ``MODEL_CARD.md`` from the run's own outputs. No number in the card is typed by hand."""

from __future__ import annotations

import pandas as pd

from .config import ExperimentConfig


def _fmt(agg: pd.DataFrame, model: str, metric: str) -> str:
    r = agg[agg.model == model]
    if r.empty:
        return "n/a"
    mu, sd = r.iloc[0][f"{metric}_mean"], r.iloc[0][f"{metric}_std"]
    return f"{mu:.3f}" if pd.isna(sd) else f"{mu:.3f} ± {sd:.3f}"


def render_model_card(cfg: ExperimentConfig, agg: pd.DataFrame, latency: list[dict], stats: dict,
                      ea: dict) -> str:
    main = ea["main"]
    b = cfg.bert
    lat = [r for r in latency if r["model"] == main]
    lat_lines = "\n".join(f"- {r['device']}, batch {r['batch_size']}: {r['ms_per_text']:.2f} ms/text "
                          f"(batch p95 {r['ms_per_batch_p95']:.1f} ms)" for r in lat) or "- not measured"
    rows = "\n".join(f"| {m} | {_fmt(agg, m, 'macro_f1')} | {_fmt(agg, m, 'accuracy')} | {_fmt(agg, m, 'ece')} |"
                     for m in agg.model)
    weakest = ", ".join(f"`{r['intent']}` ({r[f'{main}_f1']:.2f})" for r in ea["worst_classes"][:5])
    boot = ea.get("bootstrap")
    boot_line = (f"Gain over the TF-IDF baseline (seed {ea['seed']}, paired bootstrap): {boot['diff']:+.3f} macro-F1, "
                 f"95% CI [{boot['ci_low']:+.3f}, {boot['ci_high']:+.3f}]." if boot else "")
    details = (f"`{b.model_name}` fine-tuned for sequence classification (max {b.max_length} tokens, up to {b.epochs} "
               f"epochs, lr {b.lr}, batch {b.batch_size}, early stopping on validation macro-F1)"
               if main == "distilbert" else f"`{main}` (scikit-learn)")
    return f"""# Model card: Banking77 intent classifier (`{main}`)

_Generated by `textclf.model_card` from `{cfg.output_dir}`._

## Model details
- {details}.
- Base model licence: Apache-2.0 (DistilBERT). Project code: MIT.
- Trained with {len(cfg.seeds)} seeds ({cfg.seeds}); the shipped checkpoint is seed {min(cfg.seeds)}.

## Intended use
Routing English customer-support queries for a retail bank to one of {stats['n_classes']} intents, with a human
fallback. **Not** for decisions about customers (credit, fraud, account closure), and not for other languages or
domains without re-evaluation.

## Training data
Banking77 (PolyAI, CC BY 4.0): {stats['train']['rows']} train / {stats['val']['rows']} validation rows (stratified
split of the official train set, seed {cfg.data.split_seed}) and the official test set of {stats['test']['rows']} rows.
Queries are short (test mean {stats['test']['words_mean']:.1f} words, p95 {stats['test']['words_p95']:.0f}).

## Evaluation (test set, mean ± std over seeds)
| model | macro-F1 | accuracy | ECE |
|---|---|---|---|
{rows}

{boot_line}

Weakest intents: {weakest}. See `error_analysis.md` for confusions, length buckets and examples.

## Latency
{lat_lines}

## Limitations and risks
- Single-label, closed set: an out-of-scope query is always forced into one of the {stats['n_classes']} intents.
  Production use needs a confidence threshold or an out-of-scope class. The ECE column shows how far the raw
  confidences can be trusted.
- The data is crowd-written and single-domain (one bank's product set, British English spelling). Accuracy will
  drop on real customer chat with typos, code-mixing or new products.
- Several intents overlap by design (for example the card-arrival / delivery-estimate pairs). The top-confusion
  table shows which ones; merge them or ask a clarifying question instead of guessing.
- Customer queries can contain personal data. Do not log raw text without redaction.
"""
